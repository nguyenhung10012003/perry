/**
 * The PUBLIC_URL rule shared with scripts/lib/common.sh (public_url_valid) and scripts/doctor.sh: an origin only,
 * https for any host, http only for loopback, no path or trailing slash, and a port 1-65535 when present.
 */
export const PUBLIC_URL_RE = /^(https:\/\/[A-Za-z0-9.-]+|http:\/\/(localhost|127\.0\.0\.1|\[::1\]))(:[0-9]{1,5})?$/;

const PUBLIC_URL_RULE =
  'must be an origin like https://perry.example.com (https, or http://localhost for development), without a path or trailing slash';

/** Why a PUBLIC_URL value is unusable, or null. Never contains the value. */
export function publicUrlProblem(value: string | undefined): string | null {
  if (value === undefined || value === '') return 'required (see .env.example)';
  const match = PUBLIC_URL_RE.exec(value);
  if (match === null) {
    if (/^https?:\/\/[^/]+\/.*$/.test(value)) return `${PUBLIC_URL_RULE} (remove the path or trailing slash)`;
    return PUBLIC_URL_RULE;
  }
  if (match[3] !== undefined) {
    const port = Number(match[3].slice(1));
    if (port < 1 || port > 65_535) return 'has a port outside 1-65535';
  }
  return null;
}

const TRUST_KEYWORDS: Record<string, readonly [string, number, 'ipv4' | 'ipv6'][]> = {
  loopback: [
    ['127.0.0.0', 8, 'ipv4'],
    ['::1', 128, 'ipv6'],
  ],
  linklocal: [
    ['169.254.0.0', 16, 'ipv4'],
    ['fe80::', 10, 'ipv6'],
  ],
  uniquelocal: [
    ['10.0.0.0', 8, 'ipv4'],
    ['172.16.0.0', 12, 'ipv4'],
    ['192.168.0.0', 16, 'ipv4'],
    ['fc00::', 7, 'ipv6'],
  ],
};

/** WEB_TRUST_PROXY: comma list of loopback, linklocal, uniquelocal, IP addresses and CIDRs. */
export function parseTrustProxy(value: string): BlockList | string {
  const list = new BlockList();
  for (const raw of value.split(',')) {
    const item = raw.trim();
    if (item === '') continue;
    const keyword = TRUST_KEYWORDS[item];
    if (keyword !== undefined) {
      for (const [network, prefix, family] of keyword) list.addSubnet(network, prefix, family);
      continue;
    }
    const [address = '', prefixText, extra] = item.split('/');
    const family = isIP(address);
    if (family === 0 || extra !== undefined) return 'must list loopback, linklocal, uniquelocal, IP addresses or CIDRs';
    const type = family === 4 ? 'ipv4' : 'ipv6';
    if (prefixText === undefined) {
      list.addAddress(address, type);
      continue;
    }
    const prefix = Number(prefixText);
    if (!/^\d{1,3}$/.test(prefixText) || prefix > (family === 4 ? 32 : 128)) return 'has an invalid CIDR prefix';
    try {
      list.addSubnet(address, prefix, type);
    } catch {
      return 'has an invalid CIDR';
    }
  }
  return list;
}

const CLIENT_SECRET_RE = /^[A-Za-z0-9_-]{16,128}$/;

const schema = z
  .object({
    DISCORD_CLIENT_ID: z.string().regex(/^\d{17,20}$/, 'must be a Discord snowflake'),
    DISCORD_CLIENT_SECRET: optionalText.pipe(
      z.string({ error: 'required (Developer Portal > OAuth2 > Client Secret)' }).regex(CLIENT_SECRET_RE, {
        error: 'must be 16-128 characters of A-Z, a-z, 0-9, _ or -',
      }),
    ),
    PUBLIC_URL: optionalText,
    SESSION_SECRET: optionalText.pipe(
      z
        .string({ error: 'required (generated by ./scripts/setup.sh)' })
        .min(32, { error: 'must be at least 32 characters (./scripts/setup.sh generates 64 hex characters)' })
        .max(256, { error: 'must be at most 256 characters' }),
    ),
    DATABASE_URL: optionalText,
    REDIS_URL: optionalText,
    REDIS_KEY_PREFIX: z
      .string()
      .regex(/^[a-z0-9_-]{1,32}$/, 'must match [a-z0-9_-] and be 1-32 characters long')
      .default('perry'),
    DEFAULT_LOCALE: optionalText.pipe(z.enum(LOCALES).optional()).transform((value) => value ?? FALLBACK_LOCALE),
    LOG_LEVEL: z.enum(['fatal', 'error', 'warn', 'info', 'debug', 'trace', 'silent']).default('info'),
    LOG_PRETTY: booleanString.default(false),
    WEB_HOST: optionalText.pipe(z.string().max(255).optional()).transform((value) => value ?? '127.0.0.1'),
    WEB_PORT: optionalText
      .pipe(z.string().regex(/^\d{1,5}$/, 'must be a port 1-65535').optional())
      .transform((value) => (value === undefined ? 3000 : Number(value)))
      .pipe(z.number().int().min(1, 'must be a port 1-65535').max(65_535, 'must be a port 1-65535')),
    WEB_TRUST_PROXY: optionalText.transform((value) => value ?? 'loopback,uniquelocal'),
  })
  .superRefine((env, ctx) => {
    const publicUrl = publicUrlProblem(env.PUBLIC_URL);
    if (publicUrl !== null) ctx.addIssue({ code: 'custom', path: ['PUBLIC_URL'], message: publicUrl });
    const database = urlProblem(env.DATABASE_URL, POSTGRES_PROTOCOLS);
    if (database) ctx.addIssue({ code: 'custom', path: ['DATABASE_URL'], message: database });
    const redis = urlProblem(env.REDIS_URL, REDIS_PROTOCOLS);
    if (redis) ctx.addIssue({ code: 'custom', path: ['REDIS_URL'], message: redis });
    const trust = parseTrustProxy(env.WEB_TRUST_PROXY);
    if (typeof trust === 'string') ctx.addIssue({ code: 'custom', path: ['WEB_TRUST_PROXY'], message: trust });
  });

export interface WebConfig {
  readonly clientId: string;
  readonly clientSecret: string;
  /** Origin without a trailing slash. */
  readonly publicUrl: string;
  /** https PUBLIC_URL: __Host- cookie names and the Secure flag. */
  readonly secureCookies: boolean;
  readonly redirectUri: string;
  readonly sessionSecret: string;
  readonly databaseUrl: string;
  readonly redisUrl: string;
  readonly keyPrefix: string;
  readonly defaultLocale: Locale;
  readonly logLevel: 'fatal' | 'error' | 'warn' | 'info' | 'debug' | 'trace' | 'silent';
  readonly logPretty: boolean;
  readonly host: string;
  readonly port: number;
  readonly trustProxy: BlockList;
  readonly dev: boolean;
}

export type ParsedWebConfig = { ok: true; config: WebConfig } | { ok: false; error: z.ZodError };

/** Pure: validates an environment (tests pass their own). */
export function parseWebConfig(env: Record<string, string | undefined>): ParsedWebConfig {
  const parsed = schema.safeParse(env);
  if (!parsed.success) return { ok: false, error: parsed.error };
  const value = parsed.data;
  const publicUrl = value.PUBLIC_URL ?? '';
  const trustProxy = parseTrustProxy(value.WEB_TRUST_PROXY);
  if (typeof trustProxy === 'string') throw new Error('WEB_TRUST_PROXY passed validation but did not parse');
  return {
    ok: true,
    config: Object.freeze({
      clientId: value.DISCORD_CLIENT_ID,
      clientSecret: value.DISCORD_CLIENT_SECRET,
      publicUrl,
      secureCookies: publicUrl.startsWith('https://'),
      redirectUri: `${publicUrl}/auth/callback`,
      sessionSecret: value.SESSION_SECRET,
      databaseUrl: value.DATABASE_URL ?? '',
      redisUrl: value.REDIS_URL ?? '',
      keyPrefix: value.REDIS_KEY_PREFIX,
      defaultLocale: value.DEFAULT_LOCALE,
      logLevel: value.LOG_LEVEL,
      logPretty: value.LOG_PRETTY,
      host: value.WEB_HOST,
      port: value.WEB_PORT,
      trustProxy,
      dev: env.NODE_ENV !== 'production',
    }),
  };
}

/**
 * Loads the web configuration. In development only, `<cwd>/.env` is loaded first without overriding variables that
 * are already set (npm run web:* runs from the repo root, so this is the bot's file). Invalid configuration prints
 * variable names and reasons only, then exits with code 1.
 */
export function loadWebConfig(): WebConfig {
  if (process.env.NODE_ENV !== 'production') {
    const file = path.join(process.cwd(), '.env');
    if (existsSync(file)) process.loadEnvFile(file);
  }
  const parsed = parseWebConfig(process.env);
  if (!parsed.ok) exitInvalid(parsed.error);
  const { config } = parsed;
  registerSecrets(config.clientSecret, config.sessionSecret);
  registerUrlSecrets(config.databaseUrl);
  registerUrlSecrets(config.redisUrl);
  return config;
}
