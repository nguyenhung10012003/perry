// Post-build step of `npm run web:build`: turns web/.next/standalone into a self-contained directory that the image
// copies to /app/web-standalone. Plain Node, no dependencies. Exits 1 when an expected build output is missing.
import { cpSync, existsSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const webDir = dirname(fileURLToPath(import.meta.url));
const nextDir = join(webDir, '.next');
const standalone = join(nextDir, 'standalone');
const appDir = join(standalone, 'web');

function fail(message) {
  process.stderr.write(`finish-standalone: ${message}\n`);
  process.exit(1);
}

for (const required of [join(appDir, 'server.js'), join(nextDir, 'static'), join(webDir, 'public')]) {
  if (!existsSync(required)) fail(`missing ${required} (run "next build web --webpack" with output: 'standalone')`);
}

// 1. The standalone server serves static files only from its own directory.
rmSync(join(appDir, '.next', 'static'), { recursive: true, force: true });
cpSync(join(nextDir, 'static'), join(appDir, '.next', 'static'), { recursive: true });
rmSync(join(appDir, 'public'), { recursive: true, force: true });
cpSync(join(webDir, 'public'), join(appDir, 'public'), { recursive: true });

// 2. The traced root package.json declares "type": "module", but server.js is CommonJS.
writeFileSync(join(appDir, 'package.json'), '{"type":"commonjs"}\n');

// 3. server.js reads HOSTNAME and PORT, and Docker sets HOSTNAME to the container id: map the documented variables.
writeFileSync(
  join(standalone, 'start.cjs'),
  [
    '"use strict";',
    '// Generated by web/finish-standalone.mjs: maps WEB_HOST/WEB_PORT to what the Next.js standalone server reads.',
    'process.env.HOSTNAME = process.env.WEB_HOST || "127.0.0.1";',
    'process.env.PORT = process.env.WEB_PORT || "3000";',
    'require("./web/server.js");',
    '',
  ].join('\n'),
);

// 4. No source maps in the shipped output; report the size.
let bytes = 0;
let maps = 0;
function walk(dir) {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    const stat = statSync(path, { throwIfNoEntry: false });
    if (stat === undefined) continue;
    if (stat.isDirectory()) walk(path);
    else if (name.endsWith('.map')) {
      rmSync(path);
      maps += 1;
    } else bytes += stat.size;
  }
}
walk(standalone);
console.log(`finish-standalone: ${(bytes / 1024 / 1024).toFixed(1)} MB in web/.next/standalone, ${maps} source map(s) removed`);
